let selectedQuestions = [];
let currentQuestion = 0;
let score = 0;
let timer;
let timeLeft = 15;

const startScreen = document.getElementById("start-screen");
const categoryScreen = document.getElementById("category-screen");
const quizScreen = document.getElementById("quiz-screen");
const resultScreen = document.getElementById("result-screen");

const questionEl = document.getElementById("question");
const answersEl = document.getElementById("answers");
const nextBtn = document.getElementById("next-btn");
const timerEl = document.getElementById("timer");

document.getElementById("start-btn")
.addEventListener("click",()=>{

startScreen.classList.add("hidden");
categoryScreen.classList.remove("hidden");

});

document.querySelectorAll(".category-card")
.forEach(card => {

    card.addEventListener("click", () => {

        const category = card.dataset.category;

        selectedQuestions = quizData[category];

        currentQuestion = 0;
        score = 0;

        categoryScreen.classList.add("hidden");
        quizScreen.classList.remove("hidden");

        loadQuestion();

    });

});

function loadQuestion(){

timerEl.classList.remove("timer-danger");

clearInterval(timer);

timeLeft = 15;

timerEl.innerText = timeLeft;

timer = setInterval(()=>{

    timeLeft--;

    timerEl.innerText = timeLeft;

    if(timeLeft <= 5){
        timerEl.classList.add("timer-danger");
    }

    if(timeLeft === 0){

        clearInterval(timer);

        disableAnswers();

        nextBtn.style.display = "block";
    }

},1000);

let q = selectedQuestions[currentQuestion];

document.getElementById("question-number")
.innerText =
`Question ${currentQuestion+1}/${selectedQuestions.length}`;

questionEl.innerText = q.question;

answersEl.innerHTML = "";

q.answers.forEach((answer,index)=>{

const btn = document.createElement("button");

btn.innerText = answer;

btn.classList.add("answer-btn");

btn.addEventListener("click",()=>{

selectAnswer(btn,index);

});

answersEl.appendChild(btn);

});

updateProgress();

}

function selectAnswer(button,index){

clearInterval(timer);

let correctIndex =
selectedQuestions[currentQuestion].correct;

let buttons =
document.querySelectorAll(".answer-btn");

buttons.forEach(btn=>btn.disabled=true);

if(index===correctIndex){

button.classList.add("correct");
score++;

}else{

button.classList.add("wrong");
buttons[correctIndex].classList.add("correct");

}

nextBtn.style.display="block";

}

function disableAnswers(){

let buttons =
document.querySelectorAll(".answer-btn");

buttons.forEach(btn=>btn.disabled=true);

buttons[
selectedQuestions[currentQuestion].correct
].classList.add("correct");

}

nextBtn.addEventListener("click",()=>{

currentQuestion++;

if(currentQuestion < selectedQuestions.length){

loadQuestion();
nextBtn.style.display="none";

}else{

showResult();

}

});

function updateProgress(){

let progress =
((currentQuestion+1) /
selectedQuestions.length)*100;

document.getElementById("progress-bar")
.style.width = progress + "%";

}

function showResult(){

    clearInterval(timer);

    quizScreen.classList.add("hidden");
    resultScreen.classList.remove("hidden");

    let percentage =
    Math.round(
        (score / selectedQuestions.length) * 100
    );

    let performance = "";

    if(percentage >= 90){

        performance =
        "🏆 Gold Badge - Excellent";

    }
    else if(percentage >= 70){

        performance =
        "🥈 Silver Badge - Great Job";

    }
    else if(percentage >= 50){

        performance =
        "🥉 Bronze Badge - Good";

    }
    else{

        performance =
        "📚 Keep Practicing";

    }

    document.getElementById("score-text")
    .innerText =
    `${score}/${selectedQuestions.length}`;

    document.getElementById("performance")
    .innerText =
    performance;

    let circularProgress =
    document.querySelector(
    ".circular-progress"
    );

    let progressValue =
    document.querySelector(
    ".progress-value"
    );

    let progressStart = 0;

    let progress = setInterval(()=>{

        progressStart++;

        progressValue.textContent =
        `${progressStart}%`;

        circularProgress.style.background =
        `conic-gradient(
            #00dbde ${progressStart*3.6}deg,
            #fc00ff ${progressStart*3.6}deg,
            rgba(255,255,255,.2) 0deg
        )`;

        if(progressStart >= percentage){

            clearInterval(progress);

        }

    },15);

    if(percentage >= 80){

        confetti({
            particleCount:200,
            spread:120,
            origin:{y:0.6}
        });

    }

}

const text =
"Test Your Skills. Beat The Clock. Earn Badges.";

let i = 0;

function typeEffect(){

    if(i < text.length){

        document.getElementById(
        "typing-text"
        ).innerHTML += text.charAt(i);

        i++;

        setTimeout(typeEffect,60);
    }
}

